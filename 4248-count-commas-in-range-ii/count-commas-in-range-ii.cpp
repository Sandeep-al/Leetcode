class Solution {
public:
    long long countCommas(long long n) {
        // 1-999 zero commas
        // 1000-999999 1 comma
        // 1000000-999999999 2 comma
        // 1000000000-999999999999 3 comma
        // 1000000000000-999 999 999 999 999 4 comma
        // 100 000 000 000 000 0  5 comma

        if (n <= 999) {
            return 0;
        }

        if (n >= 1000 && n <= 999999) {
            return (n - 999) * 1 + (999) * 0;
        } else if (n >= 1000000 && n <= 999999999) {
            return (n - 999 - 999000) * 2 + (999000) * 1 + 999 * 0;
        } else if (n >= 1000000000 && n <= 999999999999) {
            return (n - 999000000 - 999000 - 999) * 3 + (999000000) * 2 +
                   (999000) * 1 + 999 * 0;
        } else if (n >= 1000000000000 && n <= 999999999999999) {
            return (n - 999000000000 - 999000000 - 999000 - 999) * 4 +
                   (999000000000) * 3 + (999000000) * 2 + (999000) * 1 +
                   999 * 0;
        }

        else {
            return 5+((n-1) - 999000000000 - 999000000 - 999000 - 999) * 4 +
                   (999000000000) * 3 + (999000000) * 2 + (999000) * 1 +
                   999 * 0;
        }
    }
};